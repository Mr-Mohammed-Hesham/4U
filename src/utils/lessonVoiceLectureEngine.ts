/**
 * Generates a full-length, highly-engaging pedagogical audio lecture for ANY lesson.
 * Translates all formulas into spoken words and structures the lesson like a world-class teacher.
 */
export function generateComprehensiveSpokenLessonLecture(
  lesson: any,
  context?: { grade?: string; subject?: string; unitTitle?: string }
): string {
  if (!lesson) return '';

  const rawTitle = lesson.title || 'الدرس التعليمي';
  // Clean lesson prefix if present (e.g. "الدرس 2: مفهوم النهاية" -> "مفهوم النهاية")
  const cleanTitle = rawTitle.replace(/^الدرس\s*\d+\s*:\s*/i, '').trim();

  // 1. Check if there is an exact or partial match in the curated masterclass dictionary
  for (const [key, lecture] of Object.entries(MASTERCLASS_LESSON_LECTURES)) {
    if (cleanTitle.includes(key) || key.includes(cleanTitle)) {
      return lecture;
    }
  }

  const subjectName = context?.subject || 'الرياضيات والعلوم';
  const gradeName = context?.grade || 'المرحلة الدراسية';
  const unitTitle = context?.unitTitle || '';

  // 2. Build the structured spoken lecture
  const paragraphs: string[] = [];

  // Opening Welcome & Hook
  paragraphs.push(
    `أهلاً وسهلاً بكم يا أبطال وبطلات المستقبل في هذه الحصة التعليمية الممتعة عبر منصة فور يو التعليمية. معكم الأستاذ محمد هشام، وسنشرح اليوم سوياً وبكل وضوح وبساطة درس: ${cleanTitle}، ضمن مادة ${subjectName} ${gradeName ? `لـ ${gradeName}` : ''}${unitTitle ? `، في ${unitTitle}` : ''}.`
  );

  // Lesson Intro & Core Concept
  if (lesson.content?.intro) {
    const spokenIntro = mathToSpokenArabicText(lesson.content.intro);
    paragraphs.push(
      `دعونا نبدأ بالفكرة الجوهرية لهذا الدرس: ${spokenIntro}. هذا المفهوم يعد من الأسس المحورية التي ستبنون عليها في فهم الدروس القادمة وحل المسائل التطبيقية والاختبارات الوزارية.`
    );
  } else {
    paragraphs.push(
      `يهدف هذا الدرس إلى إكسابكم الفهم العميق لأساسيات ${cleanTitle}، وربط القوانين النظرية بالتطبيقات العملية خطوة بخطوة حتى تصبحوا قادرين على حل أي مسألة بثقة واقتدار.`
    );
  }

  // Detailed Sections and Formulas
  if (lesson.content?.sections && Array.isArray(lesson.content.sections) && lesson.content.sections.length > 0) {
    paragraphs.push(`والآن يا أبطال، دعونا نستعرض العناصر والمحاور الرئيسية للدرس بالتفصيل:`);

    lesson.content.sections.forEach((sec: any, idx: number) => {
      const secTitle = sec.title ? sec.title.trim() : `المحور ${idx + 1}`;
      let secSpokenBody = '';

      if (typeof sec.content === 'string') {
        secSpokenBody = mathToSpokenArabicText(sec.content);
      } else if (Array.isArray(sec.content)) {
        secSpokenBody = sec.content
          .map((item: string, i: number) => `أولاً: ${mathToSpokenArabicText(item)}`
            .replace('أولاً', ['أولاً', 'ثانياً', 'ثالثاً', 'رابعاً', 'خامساً'][i] || 'كذلك'))
          .join('، و');
      }

      if (sec.type === 'formula' || sec.type === 'equation') {
        paragraphs.push(
          `المحور المتعلق بـ "${secTitle}": القانون الرياضي يعبر عنه بالعلاقة التالية: ${secSpokenBody}. لاحظوا جيداً دلالة كل متغير في القانون وكيف يؤثر في النتيجة النهائية.`
        );
      } else if (sec.type === 'bullets') {
        paragraphs.push(
          `أما بالنسبة لـ "${secTitle}": فأهم النقاط والشروط الأساسية التي يجب مراعاتها هي: ${secSpokenBody}.`
        );
      } else {
        paragraphs.push(
          `فيما يخص "${secTitle}": ${secSpokenBody}.`
        );
      }
    });
  }

  // Practical Advice & Exam Tips
  paragraphs.push(
    `نصيحة المعلم الذهبية لكم في هذا الدرس: عند البدء في حل أي مسألة تخص ${cleanTitle}، احرصوا دائماً على كتابة المعطيات بدقة، واختيار القانون المناسب، ومراجعة الخطوات الحسابية بهدوء لتجنب الأخطاء الشائعة.`
  );

  // Encouraging Conclusion
  paragraphs.push(
    `ختاماً يا مبدعين، التميز في ${subjectName} يأتي بالممارسة المستمرة وحل التمارين. يمكنكم الآن فتح عروض الشروحات، وبدء الاختبار الإلكتروني الذاتي لقياس مدى استيعابكم وتثبيت المعلومة. دمتم متألقين وفي أعلى المراتب دائماً!`
  );

  return paragraphs.join('\n\n');
}

