/**
 * Translates raw math and science notation into natural, clear spoken Arabic phrases.
 */
export function mathToSpokenArabicText(text: string): string {
  if (!text) return '';

  let spoken = text;

  // Limits notation
  spoken = spoken.replace(/lim\s*\(\s*x\s*→\s*([a-zA-Z0-9\+\-\_]+)\s*\⁺?\s*\)\s*f\s*\(\s*x\s*\)\s*=\s*([a-zA-Z0-9\+\-\_]+)/gi, 
    'نهاية الدالة إف أوف إكس عندما تقترب إكس من $1 تساوي $2');
  spoken = spoken.replace(/lim\s*\(\s*x\s*→\s*([a-zA-Z0-9\+\-\_]+)\s*\⁺\s*\)\s*f\s*\(\s*x\s*\)/gi, 
    'النهاية من جهة اليمين للدالة إف أوف إكس عندما تقترب إكس من $1 بقيم أكبر');
  spoken = spoken.replace(/lim\s*\(\s*x\s*→\s*([a-zA-Z0-9\+\-\_]+)\s*\⁻\s*\)\s*f\s*\(\s*x\s*\)/gi, 
    'النهاية من جهة اليسار للدالة إف أوف إكس عندما تقترب إكس من $1 بقيم أصغر');
  spoken = spoken.replace(/lim\s*\(\s*x\s*→\s*([^\)]+)\s*\)\s*([^\n\r=]+)\s*=\s*([^\n\r]+)/gi,
    'نهاية المقدار $2 عندما تقترب إكس من $1 تساوي $3');
  spoken = spoken.replace(/lim\s*\(\s*x\s*→\s*([^\)]+)\s*\)/gi, 
    'نهاية المقدار عندما تقترب إكس من $1');
  spoken = spoken.replace(/lim\s*\(\s*([a-zA-Z])\s*→\s*([^\)]+)\s*\)/gi, 
    'نهاية الدالة عندما يقترب $1 من $2');

  // Fractions in limits & algebraic expressions
  spoken = spoken.replace(/\(x²\s*-\s*4\)\s*\/\s*\(x\s*-\s*2\)/gi, 'إكس تربيع ناقص أربعة، مقسوماً على إكس ناقص اثنين');
  spoken = spoken.replace(/\(x²\s*-\s*a²\)\s*\/\s*\(x\s*-\s*a\)/gi, 'إكس تربيع ناقص إيه تربيع، مقسوماً على إكس ناقص إيه');
  spoken = spoken.replace(/lim\s*\(\s*x\s*→\s*0\s*\)\s*\(√\s*\(x\+1\)\s*-\s*1\)\s*\/\s*x/gi, 'نهاية الجذر التربيعي لإكس زائد واحد ناقص واحد الكل مقسوماً على إكس عندما تقترب إكس من الصفر');

  // Specific calculus formulas
  spoken = spoken.replace(/L\s*=\s*∫\s*√\s*\(\s*1\s*\+\s*\(dy\/dx\)²\s*\)\s*dx/gi, 'طول القوس إل يساوي تكامل الجذر التربيعي لـ واحد زائد مربع المشتقة الأولى واي بالنسبة لإكس، دي إكس');
  spoken = spoken.replace(/y\s*-\s*y₁\s*=\s*m\s*\(\s*x\s*-\s*x₁\s*\)/gi, 'معادلة المماس: واي ناقص واي واحد يساوي الميل إم مضروباً في القوس إكس ناقص إكس واحد');
  spoken = spoken.replace(/d²y\/dx²/gi, 'المشتقة الثانية لـ واي بالنسبة لإكس');
  spoken = spoken.replace(/dy\/dx/gi, 'المشتقة الأولى لـ واي بالنسبة لإكس');
  spoken = spoken.replace(/f''\(x\)/gi, 'المشتقة الثانية إف دبل برايم أوف إكس');
  spoken = spoken.replace(/f'\(x\)/gi, 'المشتقة الأولى إف برايم أوف إكس');

  // Integrals
  spoken = spoken.replace(/∫\s*([a-zA-Z0-9\+\-\_\(\)\^\*\/\s]+)\s*dx/gi, 'تكامل $1 بالنسبة لإكس');
  spoken = spoken.replace(/∫\s*([a-zA-Z0-9\+\-\_\(\)\^\*\/\s]+)\s*dt/gi, 'تكامل $1 بالنسبة للزمن تي');
  spoken = spoken.replace(/∫/g, ' تكامل ');

  // Subscripts & Points
  spoken = spoken.replace(/x₁/gi, 'إكس واحد');
  spoken = spoken.replace(/x₂/gi, 'إكس اثنين');
  spoken = spoken.replace(/y₁/gi, 'واي واحد');
  spoken = spoken.replace(/y₂/gi, 'واي اثنين');
  spoken = spoken.replace(/v₀|v_0/gi, 'السرعة الابتدائية في نود');
  spoken = spoken.replace(/v_f|v_t/gi, 'السرعة النهائية');

  // Functions & powers
  spoken = spoken.replace(/f\(x\)/gi, 'الدالة إف أوف إكس');
  spoken = spoken.replace(/g\(x\)/gi, 'الدالة جي أوف إكس');
  spoken = spoken.replace(/h\(x\)/gi, 'الدالة إتش أوف إكس');
  spoken = spoken.replace(/x²/gi, 'إكس تربيع');
  spoken = spoken.replace(/x³/gi, 'إكس تكعيب');
  spoken = spoken.replace(/y²/gi, 'واي تربيع');
  spoken = spoken.replace(/r²/gi, 'نصف القطر تربيع');
  spoken = spoken.replace(/([a-zA-Z])²/gi, '$1 تربيع');
  spoken = spoken.replace(/([a-zA-Z])³/gi, '$1 تكعيب');
  spoken = spoken.replace(/√\s*\(\s*([^\)]+)\s*\)/gi, 'الجذر التربيعي لـ $1');
  spoken = spoken.replace(/√([a-zA-Z0-9\+\-\_]+)/gi, 'الجذر التربيعي لـ $1');

  // Trigonometry
  spoken = spoken.replace(/sin\s*\(\s*([^\)]+)\s*\)|sin\s+([a-zA-Z0-9θ]+)/gi, 'جيب الزاوية ساين $1$2');
  spoken = spoken.replace(/cos\s*\(\s*([^\)]+)\s*\)|cos\s+([a-zA-Z0-9θ]+)/gi, 'جيب تمام الزاوية كوساين $1$2');
  spoken = spoken.replace(/tan\s*\(\s*([^\)]+)\s*\)|tan\s+([a-zA-Z0-9θ]+)/gi, 'ظل الزاوية تان $1$2');
  spoken = spoken.replace(/sec\s*\(\s*([^\)]+)\s*\)|sec\s+([a-zA-Z0-9θ]+)/gi, 'القاطع سيك $1$2');
  spoken = spoken.replace(/csc\s*\(\s*([^\)]+)\s*\)|csc\s+([a-zA-Z0-9θ]+)/gi, 'قاطع التمام كوسيك $1$2');
  spoken = spoken.replace(/cot\s*\(\s*([^\)]+)\s*\)|cot\s+([a-zA-Z0-9θ]+)/gi, 'ظل التمام كوتان $1$2');

  // Logarithms and exponentials
  spoken = spoken.replace(/ln\s*\(\s*([^\)]+)\s*\)|ln\s+([a-zA-Z0-9]+)/gi, 'اللوغاريتم الطبيعي لين $1$2');
  spoken = spoken.replace(/log\s*\(\s*([^\)]+)\s*\)|log\s+([a-zA-Z0-9]+)/gi, 'اللوغاريتم لوغ $1$2');
  spoken = spoken.replace(/e\^([a-zA-Z0-9\+\-]+)/gi, 'الدالة الأسية إي أس $1');

  // Physics formulas
  spoken = spoken.replace(/F\s*=\s*m\s*a|F\s*=\s*m\s*×\s*a/gi, 'القوة المحصلة إف تساوي الكتلة إم مضروبة في التسارع إيه');
  spoken = spoken.replace(/E\s*=\s*m\s*c²/gi, 'الطاقة إي تساوي الكتلة إم مضروبة في مربع سرعة الضوء سي تربيع');
  spoken = spoken.replace(/W\s*=\s*F\s*d\s*cos\s*θ|W\s*=\s*F\s*d\s*cosθ/gi, 'الشغل دبليو يساوي القوة مضروبة في الإزاحة في جيب تمام الزاوية ثيتا');
  spoken = spoken.replace(/v\s*=\s*d\s*\/\s*t/gi, 'السرعة تساوي المسافة مقسومة على الزمن');
  spoken = spoken.replace(/a\s*=\s*Δv\s*\/\s*Δt/gi, 'التسارع يساوي التغير في السرعة مقسوماً على التغير في الزمن');
  spoken = spoken.replace(/P\s*=\s*I\s*V|P\s*=\s*I\s*×\s*V/gi, 'القدرة الكهربائية تساوي شدة التيار مضروبة في فرق الجهد');
  spoken = spoken.replace(/V\s*=\s*I\s*R|V\s*=\s*I\s*×\s*R/gi, 'قانون أوم: فرق الجهد يساوي شدة التيار مضروبة في المقاومة الكهربائية');

  // Common symbols
  spoken = spoken.replace(/→/g, ' تقترب من ');
  spoken = spoken.replace(/±/g, ' موجب أو سالب ');
  spoken = spoken.replace(/≠/g, ' لا يساوي ');
  spoken = spoken.replace(/≤/g, ' أصغر من أو يساوي ');
  spoken = spoken.replace(/≥/g, ' أكبر من أو يساوي ');
  spoken = spoken.replace(/≈/g, ' تقريباً يساوي ');
  spoken = spoken.replace(/∞/g, ' المالانهاية ');
  spoken = spoken.replace(/Δ/g, ' التغير دلتا ');
  spoken = spoken.replace(/θ/g, ' الزاوية ثيتا ');
  spoken = spoken.replace(/π/g, ' النسبة التقريبية باي ');
  spoken = spoken.replace(/λ/g, ' الطول الموجي لامدا ');
  spoken = spoken.replace(/μ/g, ' معامل الاحتكاك ميو ');
  spoken = spoken.replace(/α/g, ' الزاوية ألفا ');
  spoken = spoken.replace(/β/g, ' الزاوية بيتا ');
  spoken = spoken.replace(/\s*=\s*/g, ' يساوي ');
  spoken = spoken.replace(/\s*\+\s*/g, ' زائد ');
  spoken = spoken.replace(/\s*-\s*/g, ' ناقص ');
  spoken = spoken.replace(/\s*×\s*|\s*\*\s*/g, ' مضروباً في ');
  spoken = spoken.replace(/\s*\/\s*/g, ' مقسوماً على ');

  return spoken;
}

